"""Run every (instrumentation, mode) combination in its own process and build survey/RESULTS.md.

    uv sync --group survey
    uv run python survey/run.py
"""

import importlib.metadata as md
import json
import os
import re
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).parent
OUT = HERE / "results"
LIBS = {
    "none": None,
    "otel-openai-v2": "opentelemetry-instrumentation-openai-v2",
    "openllmetry": "opentelemetry-instrumentation-openai",
    "openinference": "openinference-instrumentation-openai",
    "logfire": "logfire",
    "httpx": "opentelemetry-instrumentation-httpx",
}
# Modes each library actually has a setting for (see MODE_ENV in conftest.py).
LIB_MODES = {
    "none": ("default",),
    "otel-openai-v2": ("default", "content", "private"),
    "openllmetry": ("default", "private"),  # content is already on by default
    "openinference": ("default", "private"),  # content is already on by default
    "logfire": ("default",),  # no content opt-out; scrubbing is on by default
    "httpx": ("default",),
}
SCENARIOS = [  # (test name, label)
    ("test_secret_in_prompt", "Secret pasted in the prompt"),
    ("test_secret_in_completion", "Secret repeated in the completion"),
    ("test_secret_in_tool_call_arguments", "Secret in tool-call arguments"),
    ("test_secret_in_streamed_completion", "Secret in a streamed reply, split across chunks"),
    ("test_streamed_reply_abandoned_early", "Streamed reply abandoned after the first chunk"),
    ("test_api_key_in_auth_header", "API key in `Authorization` header"),
    ("test_api_key_in_query_string", "API key in URL query (`?key=`)"),
    ("test_error_message_echoes_key", "Error body echoes the API key"),
]


def run_all() -> dict:
    OUT.mkdir(exist_ok=True)
    results = {}
    for lib in LIBS:
        for mode in LIB_MODES[lib]:
            report = OUT / f"{lib}-{mode}.json"
            env = os.environ | {"SURVEY_LIB": lib, "SURVEY_MODE": mode}
            subprocess.run([sys.executable, "-m", "pytest", str(HERE), "-q", "-p", "no:cacheprovider",
                            "-W", "ignore", "--traceleak", f"--traceleak-report={report}"],
                           env=env, cwd=HERE.parent, capture_output=True)
            results[(lib, mode)] = json.loads(report.read_text()) if report.exists() else None
    return results


def _field(f: dict) -> str:
    """Human name of where a finding sits: the innermost attribute key, else the OTLP field."""
    keys = re.findall(r"attributes\[([^\]]+)\]", f["path"])
    if keys:
        name = keys[-1]
        if f["path"].count("attributes[") > 1:  # e.g. an attribute on a span event
            name = f"{keys[0]} › {name}"
    elif ".body" in f["path"]:
        name = "log body"
    else:
        name = f["path"].rsplit(".", 2)[-1] if not f["path"].endswith("status.message") else "status.message"
    return f"{f['signal'][:-1]}: {name}"


# Configs where message content is supposed to be captured. In these, a "clean" content scenario
# means the capture setting silently did nothing; the first run hit exactly that with openai-v2 `=true`.
CAPTURES_CONTENT = {("otel-openai-v2", "content"), ("openllmetry", "default"),
                    ("openinference", "default"), ("logfire", "default")}
# Non-streamed only: these validate the capture config itself; streaming results are findings.
CONTENT_SCENARIOS = {"test_secret_in_prompt", "test_secret_in_completion", "test_secret_in_tool_call_arguments"}


def cell(report: dict | None, test: str, config: tuple[str, str]) -> str:
    if report is None:
        return "run failed"
    for r in report["results"]:
        if r["nodeid"].endswith("::" + test):
            if r["status"] == "clean" and config in CAPTURES_CONTENT and test in CONTENT_SCENARIOS:
                return "MISCONFIGURED (capture expected, nothing captured)"
            if r["status"] != "leak":
                return r["status"]
            fields = sorted({_field(f) for f in r["findings"]})
            return "**LEAK** " + "<br>".join(f"`{f}`" for f in fields)
    return "not run"


def render(results: dict) -> str:
    versions = {"openai": md.version("openai"), "opentelemetry-sdk": md.version("opentelemetry-sdk")}
    versions |= {pkg: md.version(pkg) for pkg in LIBS.values() if pkg}
    cols = [(lib, mode) for lib in LIBS for mode in LIB_MODES[lib]]
    lines = ["# Instrumentation leak survey", "",
             "Each cell is traceleakcheck's verdict for one scenario. `content` = the library's "
             "documented content-capture opt-in is set. Generated by `survey/run.py`.", "",
             "| Scenario | " + " | ".join(f"{lib}<br>{mode}" for lib, mode in cols) + " |",
             "|---|" + "---|" * len(cols)]
    for test, label in SCENARIOS:
        lines.append(f"| {label} | " + " | ".join(cell(results[c], test, c) for c in cols) + " |")
    lines += ["", "Versions: " + ", ".join(f"{k} {v}" for k, v in versions.items()), ""]
    return "\n".join(lines)


if __name__ == "__main__":
    res = run_all()
    (HERE / "RESULTS.md").write_text(render(res), encoding="utf-8")
    json.dump({f"{lib}/{mode}": r for (lib, mode), r in res.items()}, open(OUT / "all.json", "w"), indent=2)
    print((HERE / "RESULTS.md").read_text(encoding="utf-8"))
